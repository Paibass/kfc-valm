CREATE TABLE IF NOT EXISTS listas_precios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL UNIQUE,
  activa BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS locales (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo TEXT NOT NULL UNIQUE,
  nombre TEXT NOT NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  lista_precios_id BIGINT REFERENCES listas_precios(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS cajeros (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  local_id BIGINT NOT NULL REFERENCES locales(id),
  nombre TEXT NOT NULL,
  usuario_pos TEXT,
  es_referente BOOLEAN NOT NULL DEFAULT FALSE,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  UNIQUE (local_id, nombre)
);

CREATE TABLE IF NOT EXISTS productos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo TEXT NOT NULL UNIQUE,
  nombre TEXT NOT NULL,
  categoria TEXT NOT NULL,
  tipo TEXT NOT NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS precios_producto (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  producto_id BIGINT NOT NULL REFERENCES productos(id),
  lista_precios_id BIGINT NOT NULL REFERENCES listas_precios(id),
  precio NUMERIC(12, 2) NOT NULL CHECK (precio >= 0),
  activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE UNIQUE INDEX IF NOT EXISTS precios_producto_activo_unico
  ON precios_producto (producto_id, lista_precios_id)
  WHERE activo = TRUE;

CREATE TABLE IF NOT EXISTS integraciones_local (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  local_id BIGINT NOT NULL REFERENCES locales(id),
  google_form_action TEXT,
  google_form_fields JSONB NOT NULL DEFAULT '{}'::jsonb,
  apps_script_url TEXT,
  spreadsheet_url TEXT,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  UNIQUE (local_id)
);
